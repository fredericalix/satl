/// Maximum size of any message on the internal gRPC protocol
/// (architecture §15).
///
/// Apply it explicitly on both ends — tonic's defaults are not this value:
/// `.max_decoding_message_size(MAX_MESSAGE_SIZE)` and
/// `.max_encoding_message_size(MAX_MESSAGE_SIZE)` on every generated client and
/// server. Everything that batches or chunks in this protocol (assignment
/// batches, status batches, raft snapshot chunks) exists to stay under it.
pub const MAX_MESSAGE_SIZE: usize = 4 * 1024 * 1024;

#[cfg(test)]
mod tests {
    use super::{health, v1};

    /// The sparse SwarmKit values (architecture §4, SWK §4.2) are the contract
    /// between the wire, the Raft store and the agent's on-disk task database.
    /// If this test fails, the wire and the store have stopped agreeing.
    #[test]
    fn task_state_values_match_the_swarmkit_table() {
        let expected = [
            (v1::TaskState::New, 0),
            (v1::TaskState::Pending, 64),
            (v1::TaskState::Assigned, 192),
            (v1::TaskState::Accepted, 256),
            (v1::TaskState::Preparing, 320),
            (v1::TaskState::Ready, 384),
            (v1::TaskState::Starting, 448),
            (v1::TaskState::Running, 512),
            (v1::TaskState::Complete, 576),
            (v1::TaskState::Shutdown, 640),
            (v1::TaskState::Failed, 704),
            (v1::TaskState::Rejected, 768),
            (v1::TaskState::Remove, 800),
            (v1::TaskState::Orphaned, 832),
        ];
        for (state, value) in expected {
            assert_eq!(state as i32, value, "{state:?}");
        }
    }

    /// Desired states reuse the observed-state numbering so the two compare on
    /// one scale (architecture §4 rule 3).
    #[test]
    fn desired_state_values_line_up_with_task_state() {
        let pairs = [
            (v1::DesiredState::Ready, v1::TaskState::Ready),
            (v1::DesiredState::Running, v1::TaskState::Running),
            (v1::DesiredState::Complete, v1::TaskState::Complete),
            (v1::DesiredState::Shutdown, v1::TaskState::Shutdown),
            (v1::DesiredState::Remove, v1::TaskState::Remove),
        ];
        for (desired, observed) in pairs {
            assert_eq!(desired as i32, observed as i32, "{desired:?}");
        }
        assert_eq!(v1::DesiredState::Unspecified as i32, 0);
    }

    /// proto3 enums are open: an unknown value arrives as a bare `i32` and
    /// `try_from` is the only thing standing between it and a wrong decision.
    /// The implementing wave must reject both unknown and `UNSPECIFIED`.
    #[test]
    fn unknown_enum_values_do_not_decode() {
        assert!(v1::TaskState::try_from(513).is_err());
        assert!(v1::NodeRole::try_from(99).is_err());
        assert_eq!(
            v1::NodeRole::try_from(0),
            Ok(v1::NodeRole::Unspecified),
            "UNSPECIFIED decodes; callers must still treat it as a protocol error"
        );
    }

    /// The envelopes carry an opaque CBOR payload plus routing mirrors; this
    /// pins the shape so a later "helpful" re-modelling of the domain into
    /// protobuf shows up as a failing test rather than as drift.
    #[test]
    fn task_envelope_carries_an_opaque_payload_and_routing_mirrors() {
        let task = v1::Task {
            id: "1hvy0lj3x0b883f8e30fyp217".to_owned(),
            meta: Some(v1::Meta {
                version: Some(v1::Version { index: 42 }),
                created_at: None,
                updated_at: None,
            }),
            state: v1::TaskState::Running as i32,
            desired_state: v1::DesiredState::Running as i32,
            payload: vec![0xa0], // CBOR empty map
        };
        assert_eq!(task.state(), v1::TaskState::Running);
        assert_eq!(task.desired_state(), v1::DesiredState::Running);
        assert_eq!(task.payload, vec![0xa0]);
    }

    /// Assignment changes are a oneof of the three shipped object kinds; a
    /// REMOVE only needs the ID.
    #[test]
    fn assignment_change_models_remove_by_id() {
        let change = v1::AssignmentChange {
            assignment: Some(v1::Assignment {
                item: Some(v1::assignment::Item::Secret(v1::Secret {
                    id: "sec".to_owned(),
                    meta: None,
                    payload: Vec::new(),
                })),
            }),
            action: v1::assignment_change::Action::Remove as i32,
        };
        assert_eq!(change.action(), v1::assignment_change::Action::Remove);
        match change.assignment.and_then(|a| a.item) {
            Some(v1::assignment::Item::Secret(s)) => {
                assert_eq!(s.id, "sec");
                assert!(s.payload.is_empty());
            }
            other => panic!("expected a secret assignment, got {other:?}"),
        }
    }

    /// The health service is the upstream `grpc.health.v1` shape, so external
    /// probes work unchanged.
    #[test]
    fn health_serving_status_matches_upstream() {
        use health::health_check_response::ServingStatus;
        assert_eq!(ServingStatus::Unknown as i32, 0);
        assert_eq!(ServingStatus::Serving as i32, 1);
        assert_eq!(ServingStatus::NotServing as i32, 2);
        assert_eq!(ServingStatus::ServiceUnknown as i32, 3);
    }
}
