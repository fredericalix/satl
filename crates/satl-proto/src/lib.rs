//! Generated tonic code for SatL's internal node-to-node gRPC protocol.
//!
//! The protocol definition lives in `proto/` at the repository root and is
//! described in `docs/architecture.md` §7 (internal protocols). This crate is
//! only the generated transport: it holds no logic, and the servers and clients
//! are implemented by the crates that own each concern —
//! `satld`/`satl-agent` (dispatcher), `satl-ca` (`NodeCA`), `satl-cluster`
//! (Raft, Control).
//!
//! # Scope
//!
//! **This protocol is internal only.** It is spoken between SatL nodes over
//! mTLS and is never exposed to clients; the Docker Engine REST API is the
//! external surface (`docs/api-compat.md`, architecture §13).
//!
//! # Services
//!
//! | Service | Role required | Defined in | Reference |
//! |---|---|---|---|
//! | [`Dispatcher`](v1::dispatcher_server::Dispatcher) | worker or manager | `proto/dispatcher.proto` | architecture §7.1, SWK §13 |
//! | [`NodeCA`](v1::node_ca_server::NodeCa) | none (bootstrap) / any | `proto/ca.proto` | architecture §12.2–§12.3, SWK §16.2–§16.3 |
//! | [`Raft`](v1::raft_server::Raft) | manager | `proto/raft.proto` | architecture §6, SWK §11.7 |
//! | [`Control`](v1::control_server::Control) | manager | `proto/control.proto` | architecture §6.5–§6.6, SWK §11.3, §11.5 |
//! | [`Health`](health::health_server::Health) | any | `proto/health.proto` | architecture §7 |
//!
//! # Payloads are opaque
//!
//! Store objects and openraft messages travel as `bytes` holding the CBOR
//! (`ciborium`) encoding of the corresponding `satl-core` / openraft type,
//! alongside the few scalars the protocol routes on. The rationale and the
//! tradeoff are written up at the top of `proto/common.proto` and in
//! `proto/README.md`; the short version is that `satl-core` stays the single
//! source of truth for the domain model, at the cost of cross-language
//! clients — which an internal protocol does not need.
//!
//! Every `bytes` payload in this crate is CBOR of the Rust type named in the
//! `.proto` comment. Changing that codec is a breaking change and requires a
//! new package version (`satl.internal.v2`).
//!
//! # Limits
//!
//! Messages are capped at 4 MiB (architecture §15). That bound is what forces
//! assignment batching (100 changes / 100 ms), status batching, and snapshot
//! chunking to exist at all — see the per-service comments in `proto/`.

